import sys
import asyncio

from PyQt5.QtWidgets import QApplication
import qasync

from ui.main_window import MainWindow


def main():
    app = QApplication(sys.argv)
    loop = qasync.QEventLoop(app)
    asyncio.set_event_loop(loop)

    window = MainWindow()
    window.show()

    with loop:
        loop.run_forever()


if __name__ == "__main__":
    main()
